import './demos.css';
import { mountQueue } from './apps/queue';
import { routingExamples } from './examples';
import { navigation } from './navigation';
import { createSession } from './session';
const root = document.querySelector<HTMLElement>('#app')!;
let session: ReturnType<typeof createSession>;
mountQueue(root, { samples: routingExamples.slice(0, 4), predict: sample => session.predict(sample) });
const status = navigation(root.querySelector<HTMLElement>('.queue-header')!, 'queue');
session = createSession(status);
window.addEventListener('pagehide', () => { void session.dispose(); });
window.addEventListener('pageshow', event => { if (event.persisted) session = createSession(status); });
